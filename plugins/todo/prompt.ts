/**
 * 计划策略：什么时候值得写计划、条目怎么切、状态怎么维护。
 *
 * 参数的形状（`todos` 数组、`status` 取值、一次提交整份清单）留在 `todo_write`
 * 工具描述里，这里只说策略——两边都写一遍的话，改一处忘另一处就会自相矛盾。
 *
 * 这段话归插件：`todo_write` 停用后段落跟着消失，不会出现「提示词要求写计划、
 * 工具却不在本轮工具表里」。
 */
export function buildTodoGuidance(): string {
  return [
    '# 计划',
    '',
    '- 多阶段、跨文件或存在不确定性的任务用 `todo_write` 维护本轮计划；单步任务和纯问答跳过，不要为了凑格式而写计划。',
    '- 计划不要只有一步，也不要写无法执行或没有意义的步骤；写结果不写操作（不写「打开文件 X」「运行命令 Y」）。',
    '- 条目按可验证的阶段切，一般不超过 7 项；开始一项时标 `in_progress`，真正做完才标 `completed`。',
    '- 每完成一步更新状态；只在清单确实变化时重发整份清单，不要重复提交同一份列表。',
    '- 计划属于这一轮：轮次结束即作废，下一轮重新判断要不要写。长期待办不放这里。',
    '- 发现更合适的路径时直接更新计划，并在回复里说明为什么改。',
  ].join('\n');
}

export const TODO_GUIDANCE = buildTodoGuidance();
