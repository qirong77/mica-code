/**
 * Maccy 风格的剪贴板历史业务模型：纯函数，不碰 fs、不碰剪贴板、不碰时钟（时间一律由调用方传入）。
 *
 * 约定：
 * - 设置项来自插件清单（`plugin.json` 的 `settings`，值都是字符串），`normalizeSettings()` 是唯一的解析与夹取入口。
 * - `state.items` 按「新条目在前」维持顺序；显示排序由 `searchHistory()` 按 `sortBy` 现算。
 * - 固定（pinned）条目不受条数上限与保留期约束，也不会被 `recordCapture()` 的淘汰碰到。
 * - 持久化形态是 `{ schemaVersion: 1, items, paused, ignoreNext }`；未知 `schemaVersion` 直接拒绝（抛错），
 *   不做旧形态兼容。
 * - 全文正文默认不落盘：`searchHistory()` 的第 4 个参数是 `Map<id, 全文>`，由调用方在查询时按需加载。
 *   `metadata.searchText` 只是可选旁路（上限 10000 字），不传就不会写进状态。
 * - 采集快照只有一种形态（`native-source.js` 的输出）：`{ types, source: { name, bundleId },
 *   items: [{ types: [{ type, data }] }], text?, files?: string[], imageWidth?, imageHeight?, kind? }`。
 *   文件路径与图片尺寸在快照顶层，没有嵌套的 `native`。
 */

import { createHash } from 'node:crypto';

export const SCHEMA_VERSION = 1;

/** 固定（pinned）条目占用的快捷键，稳定分配、不重复。 */
export const PIN_KEYS = Object.freeze('abcdefghijklmnopqrstuvwxyz'.split(''));

export const SEARCH_MODES = Object.freeze(['fuzzy', 'simple', 'regexp']);
export const SORT_FIELDS = Object.freeze(['lastCopiedAt', 'firstCopiedAt', 'copyCount']);
export const HISTORY_FILTERS = Object.freeze(['all', 'pinned', 'text', 'image', 'files']);
export const CAPTURE_KINDS = Object.freeze(['text', 'image', 'files']);

/**
 * 永远不可取消的忽略类型（Maccy 的行为一致）：瞬时、隐藏、自动生成三种标记一旦出现就说明
 * 「这段内容不该进历史」，用户没有理由推翻它。
 */
export const LOCKED_IGNORED_TYPES = Object.freeze([
  'org.nspasteboard.TransientType',
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.AutoGeneratedType',
]);

/** 默认的额外忽略类型（用户可在设置里增删），与 Maccy 的出厂清单一致。 */
export const DEFAULT_IGNORED_TYPES = Object.freeze([
  'com.agilebits.onepassword',
  'com.typeit4me.clipping',
  'de.petermaurer.TransientPasteboardType',
  'Pasteboard generator type',
  'net.antelle.keeweb',
]);

/** 插件自己写回剪贴板时打的标记：再采一次就是自激循环，直接跳过。 */
export const SELF_PASTEBOARD_TYPE = 'org.mica.maccy';

/** Universal Clipboard 的来源标记（同一份内容在另一台 Mac 上）。 */
const UNIVERSAL_CLIPBOARD_TYPES = Object.freeze(['com.apple.is-remote-clipboard']);

/** 与内容身份无关的 marker：算 contentId 时剔掉，否则同一个东西换个来路就变另一个 id。 */
const HASH_IRRELEVANT_TYPES = new Set(
  [SELF_PASTEBOARD_TYPE, ...LOCKED_IGNORED_TYPES].map((type) => type.toLowerCase()),
);

const TEXT_TYPES = new Set([
  'public.utf8-plain-text',
  'public.utf16-plain-text',
  'public.utf16-external-plain-text',
  'public.plain-text',
  'public.text',
  'public.html',
  'public.rtf',
  'public.rtfd',
  'com.apple.flat-rtfd',
  'com.apple.rtfd',
  'nsstringpboardtype',
  'utf8-plain-text',
  'text/plain',
  'text/html',
  'text/rtf',
]);

const IMAGE_TYPES = new Set([
  'public.png',
  'public.tiff',
  'public.jpeg',
  'public.jpeg-2000',
  'public.heic',
  'public.image',
  'png',
  'tiff',
  'image/png',
  'image/jpeg',
  'image/tiff',
  'image/heic',
]);

const FILE_TYPES = new Set(['public.file-url', 'nsfilenamespboardtype', 'public.directory']);

const HEX_ID = /^[0-9a-f]{64}$/;
const PIN_KEY = /^[a-z]$/;

export const TITLE_LIMIT = 120;
export const PREVIEW_LIMIT = 500;
export const SEARCH_TEXT_LIMIT = 10_000;
const MAX_ITEM_BYTES_MIN = Math.round(0.1 * 1024 * 1024);
const MAX_ITEM_BYTES_MAX = 20 * 1024 * 1024;

export const DEFAULT_SETTINGS = Object.freeze({
  historySize: 500,
  maxItemBytes: 5 * 1024 * 1024,
  // 默认只留最近 31 天：历史自己会过期，不需要用户记得来清。
  retentionDays: 31,
  searchMode: 'fuzzy',
  sortBy: 'lastCopiedAt',
  pasteAutomatically: false,
  removeFormatting: false,
  showFooter: true,
  showPreview: true,
  ignoreEvents: false,
  ignoredApplications: Object.freeze([]),
  ignoredTypes: Object.freeze([...LOCKED_IGNORED_TYPES, ...DEFAULT_IGNORED_TYPES]),
  ignoreUniversalClipboard: false,
  clipboardCheckInterval: 500,
});

/* ---------------------------------------------------------------------------
 * 通用小工具
 * ------------------------------------------------------------------------- */

function textOf(value) {
  if (typeof value === 'string') return value;
  if (value == null) return '';
  return String(value);
}

function clampInt(value, min, max, fallback) {
  if (value == null) return fallback;
  if (typeof value === 'string' && value.trim() === '') return fallback;
  const num = typeof value === 'number' ? value : Number(textOf(value).trim());
  if (!Number.isFinite(num)) return fallback;
  const int = Math.trunc(num);
  if (int < min) return min;
  if (int > max) return max;
  return int;
}

/** 截断到 `limit` 个字符（按码点算，带省略号时总长也不超）。 */
function clampText(value, limit) {
  const trimmed = textOf(value).trim();
  if (!trimmed) return '';
  const chars = Array.from(trimmed);
  if (chars.length <= limit) return trimmed;
  return `${chars.slice(0, limit - 1).join('')}…`;
}

function collapseSpaces(value) {
  return textOf(value)
    .replace(/[\s\u00a0]+/g, ' ')
    .trim();
}

function firstLine(value) {
  for (const line of textOf(value).split(/\r?\n/)) {
    const collapsed = collapseSpaces(line);
    if (collapsed) return collapsed;
  }
  return '';
}

function normalizeSource(raw) {
  const source = raw && typeof raw === 'object' ? raw : {};
  return {
    name: textOf(source.name).trim(),
    bundleId: textOf(source.bundleId).trim(),
  };
}

function normalizeId(value) {
  const id = textOf(value).trim().toLowerCase();
  return HEX_ID.test(id) ? id : '';
}

/** 简单 glob：`*` 任意串、`?` 单个字符，其余按字面量；调用方负责大小写归一。 */
function globToRegExp(pattern) {
  let source = '';
  for (const char of pattern) {
    if (char === '*') source += '[\\s\\S]*';
    else if (char === '?') source += '[\\s\\S]';
    else source += char.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${source}$`, 'u');
}

function globMatch(pattern, value) {
  if (!pattern) return false;
  if (pattern === value) return true;
  if (!pattern.includes('*') && !pattern.includes('?')) return false;
  try {
    return globToRegExp(pattern).test(value);
  } catch {
    return false;
  }
}

function base64ByteLength(data) {
  if (typeof data !== 'string') return 0;
  let value = data;
  const marker = value.indexOf(';base64,');
  if (value.startsWith('data:') && marker >= 0) value = value.slice(marker + 8);
  value = value.replace(/\s+/g, '');
  if (!value) return 0;
  let padding = 0;
  if (value.endsWith('==')) padding = 2;
  else if (value.endsWith('=')) padding = 1;
  return Math.max(0, Math.floor((value.length * 3) / 4) - padding);
}

function utf8ByteLength(text) {
  return Buffer.byteLength(textOf(text), 'utf8');
}

function fileNameOf(entry) {
  let value = '';
  if (typeof entry === 'string') value = entry;
  else if (entry && typeof entry === 'object') value = textOf(entry.name || entry.path);
  value = value.trim();
  if (!value) return '';
  if (value.startsWith('file://')) {
    try {
      value = decodeURIComponent(value.slice('file://'.length));
    } catch {
      value = value.slice('file://'.length);
    }
  }
  const trimmed = value.replace(/[\\/]+$/, '');
  const index = Math.max(trimmed.lastIndexOf('/'), trimmed.lastIndexOf('\\'));
  return index >= 0 ? trimmed.slice(index + 1) : trimmed;
}

/* ---------------------------------------------------------------------------
 * 设置
 * ------------------------------------------------------------------------- */

function readFlag(raw, key, fallback) {
  const value = raw[key];
  if (typeof value === 'boolean') return value;
  if (typeof value === 'number') return value !== 0;
  const text = textOf(value).trim().toLowerCase();
  if (!text) return fallback;
  if (['true', '1', 'on', 'yes'].includes(text)) return true;
  if (['false', '0', 'off', 'no'].includes(text)) return false;
  return fallback;
}

function readChoice(raw, key, allowed, fallback) {
  const text = textOf(raw[key]).trim().toLowerCase();
  if (!text) return fallback;
  for (const option of allowed) {
    if (option.toLowerCase() === text) return option;
  }
  return fallback;
}

function readList(value) {
  const entries = Array.isArray(value) ? value : textOf(value).split(/\r?\n/);
  const seen = new Set();
  const list = [];
  for (const entry of entries) {
    const item = textOf(entry).trim();
    if (!item) continue;
    const key = item.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    list.push(item);
  }
  return list;
}

/**
 * 清单的 string values → 生效设置。
 * 非法 / 缺省的值一律回落到默认值再夹到区间内，不抛错；`maxItemSizeMiB` 是清单里的档位名，
 * 换算成字节后存在 `maxItemBytes`（0.1–20 MiB）。
 *
 * 两个清单（`ignoredApplications` / `ignoredTypes`）都是换行分隔的文本。`ignoredTypes` 只有
 * **没设置**（`undefined` / `null`）时才展开成 `DEFAULT_IGNORED_TYPES`（Maccy 的出厂清单）；
 * 显式写成空串 / 空数组是用户「把可选的 5 条全删了」的意思，只留 `LOCKED_IGNORED_TYPES` 三项。
 * 三项 locked 无论如何都在生效清单里。幂等：把这份结果再传回来还是同一份。
 */
export function normalizeSettings(raw) {
  const source = raw && typeof raw === 'object' ? raw : {};

  let maxItemBytes = DEFAULT_SETTINGS.maxItemBytes;
  const mib = source.maxItemSizeMiB;
  if (mib != null && textOf(mib).trim() !== '') {
    const num = Number(textOf(mib).trim());
    if (Number.isFinite(num)) {
      maxItemBytes = Math.round(Math.min(20, Math.max(0.1, num)) * 1024 * 1024);
    }
  } else if (source.maxItemBytes != null && textOf(source.maxItemBytes).trim() !== '') {
    maxItemBytes = clampInt(source.maxItemBytes, MAX_ITEM_BYTES_MIN, MAX_ITEM_BYTES_MAX, DEFAULT_SETTINGS.maxItemBytes);
  }

  const hasIgnoredTypes = source.ignoredTypes != null;
  const userIgnoredTypes = readList(source.ignoredTypes);
  const ignoredTypes = readList([
    ...LOCKED_IGNORED_TYPES,
    ...(hasIgnoredTypes ? userIgnoredTypes : DEFAULT_IGNORED_TYPES),
  ]);

  return {
    historySize: clampInt(source.historySize, 1, 10_000, DEFAULT_SETTINGS.historySize),
    maxItemBytes,
    retentionDays: clampInt(source.retentionDays, 0, 365, DEFAULT_SETTINGS.retentionDays),
    searchMode: readChoice(source, 'searchMode', SEARCH_MODES, DEFAULT_SETTINGS.searchMode),
    sortBy: readChoice(source, 'sortBy', SORT_FIELDS, DEFAULT_SETTINGS.sortBy),
    pasteAutomatically: readFlag(source, 'pasteAutomatically', DEFAULT_SETTINGS.pasteAutomatically),
    removeFormatting: readFlag(source, 'removeFormatting', DEFAULT_SETTINGS.removeFormatting),
    showFooter: readFlag(source, 'showFooter', DEFAULT_SETTINGS.showFooter),
    showPreview: readFlag(source, 'showPreview', DEFAULT_SETTINGS.showPreview),
    ignoreEvents: readFlag(source, 'ignoreEvents', DEFAULT_SETTINGS.ignoreEvents),
    ignoredApplications: readList(source.ignoredApplications),
    ignoredTypes,
    ignoreUniversalClipboard: readFlag(source, 'ignoreUniversalClipboard', DEFAULT_SETTINGS.ignoreUniversalClipboard),
    clipboardCheckInterval: clampInt(source.clipboardCheckInterval, 100, 5000, DEFAULT_SETTINGS.clipboardCheckInterval),
  };
}

/* ---------------------------------------------------------------------------
 * 采集判定
 * ------------------------------------------------------------------------- */

/**
 * 采集层放在快照顶层的原生信息：`files`（绝对路径）与 `imageWidth` / `imageHeight`。
 * 只有这一种形态——`native-source.js` 就是这么给的，没有别的历史形态需要兼容。
 */
function readNative(snapshot) {
  const files = (Array.isArray(snapshot?.files) ? snapshot.files : []).map(fileNameOf).filter(Boolean);
  const width = Number(snapshot?.imageWidth);
  const height = Number(snapshot?.imageHeight);
  return {
    files,
    imageWidth: Number.isFinite(width) ? width : 0,
    imageHeight: Number.isFinite(height) ? height : 0,
  };
}

function collectTypes(snapshot) {
  const types = [];
  const seen = new Set();
  const push = (value) => {
    const type = textOf(value).trim();
    if (!type) return;
    const key = type.toLowerCase();
    if (seen.has(key)) return;
    seen.add(key);
    types.push(key);
  };
  for (const type of Array.isArray(snapshot.types) ? snapshot.types : []) push(type);
  for (const item of Array.isArray(snapshot.items) ? snapshot.items : []) {
    for (const entry of Array.isArray(item?.types) ? item.types : []) push(entry?.type);
  }
  return types;
}

function snapshotText(snapshot) {
  return typeof snapshot?.text === 'string' ? snapshot.text : '';
}

function kindFromTypes(types, native, text) {
  if (native.files.length) return 'files';
  let hasFiles = false;
  let hasImage = false;
  let hasText = false;
  for (const type of types) {
    const lower = type.toLowerCase();
    if (FILE_TYPES.has(lower)) hasFiles = true;
    else if (IMAGE_TYPES.has(lower) || lower.startsWith('image/')) hasImage = true;
    else if (TEXT_TYPES.has(lower) || lower.startsWith('text/') || lower.startsWith('public.utf8')) hasText = true;
  }
  if (hasFiles) return 'files';
  if (hasImage || (native.imageWidth > 0 && native.imageHeight > 0)) return 'image';
  if (hasText || text.trim()) return 'text';
  return '';
}

function hasPayload(snapshot) {
  for (const item of Array.isArray(snapshot.items) ? snapshot.items : []) {
    for (const entry of Array.isArray(item?.types) ? item.types : []) {
      if (typeof entry?.data === 'string' && entry.data.trim()) return true;
    }
  }
  return false;
}

function matchesIgnoredApplication(source, patterns) {
  const fields = [textOf(source?.name).trim(), textOf(source?.bundleId).trim()]
    .filter(Boolean)
    .map((value) => value.toLowerCase());
  if (!fields.length) return false;
  for (const pattern of Array.isArray(patterns) ? patterns : []) {
    const needle = textOf(pattern).trim().toLowerCase();
    if (!needle) continue;
    for (const field of fields) {
      if (globMatch(needle, field)) return true;
    }
  }
  return false;
}

/**
 * 这次剪贴板变化要不要进历史？true = 丢弃。
 *
 * 顺序：全局忽略 → 空内容 → 自己写回的标记 → 未知 / 纯不支持类型 → 命中忽略类型 →
 * Universal Clipboard → 忽略的应用。
 */
export function shouldIgnoreCapture(snapshot, settings) {
  const config = normalizeSettings(settings);
  if (config.ignoreEvents) return true;

  const snap = snapshot && typeof snapshot === 'object' ? snapshot : {};
  const native = readNative(snap);
  const types = collectTypes(snap);
  const text = snapshotText(snap);

  if (!text.trim() && !hasPayload(snap) && !native.files.length) return true;
  if (types.includes(SELF_PASTEBOARD_TYPE.toLowerCase())) return true;
  if (!kindFromTypes(types, native, text)) return true;

  const ignored = new Set(config.ignoredTypes.map((type) => type.toLowerCase()));
  for (const type of types) {
    if (ignored.has(type)) return true;
  }

  if (config.ignoreUniversalClipboard) {
    for (const type of UNIVERSAL_CLIPBOARD_TYPES) {
      if (types.includes(type.toLowerCase())) return true;
    }
  }

  return matchesIgnoredApplication(snap.source, config.ignoredApplications);
}

/* ---------------------------------------------------------------------------
 * 内容身份
 * ------------------------------------------------------------------------- */

/**
 * 同一份内容的稳定 id：sha256(逐条目的「类型排序后的 type + data」)。
 * 与来源应用、时间、条目在历史里的位置无关；`org.mica.maccy` 与 nspasteboard 的 marker 不参与哈希。
 */
export function contentId(items) {
  const hash = createHash('sha256');
  for (const item of Array.isArray(items) ? items : []) {
    const entries = [];
    for (const entry of Array.isArray(item?.types) ? item.types : []) {
      const type = textOf(entry?.type).trim();
      if (!type || HASH_IRRELEVANT_TYPES.has(type.toLowerCase())) continue;
      entries.push([type, textOf(entry?.data).replace(/\s+/g, '')]);
    }
    entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
    hash.update(`i${entries.length}\n`);
    for (const [type, data] of entries) {
      hash.update(`${type.length}:${type}\n`);
      hash.update(`${data.length}:${data}\n`);
    }
  }
  return hash.digest('hex');
}

/* ---------------------------------------------------------------------------
 * 采集摘要
 * ------------------------------------------------------------------------- */

/** 所有 payload 表示的实际字节之和：一段内容可能同时带纯文本 / HTML / RTF / 图片，都得算进上限。 */
function payloadBytes(snapshot) {
  let bytes = 0;
  for (const item of Array.isArray(snapshot.items) ? snapshot.items : []) {
    for (const entry of Array.isArray(item?.types) ? item.types : []) {
      bytes += base64ByteLength(entry?.data);
    }
  }
  return bytes;
}

/**
 * 采集到的一段内容长什么样：给历史条目用的标题 / 预览 / 大小 / 来源。
 * `snapshot.kind` 合法时直接采信（采集层已经判过），否则按类型推导（files > image > text）。
 * `bytes` 是所有 payload 表示的字节之和（富文本的多表示一起算，对应 `maxItemBytes`）；
 * 只有完全没有 payload 时才用文本的 utf8 长度兜底。
 */
export function describeCapture(snapshot) {
  const snap = snapshot && typeof snapshot === 'object' ? snapshot : {};
  const native = readNative(snap);
  const types = collectTypes(snap);
  const text = snapshotText(snap);
  const kind = CAPTURE_KINDS.includes(snap.kind) ? snap.kind : kindFromTypes(types, native, text) || 'text';

  let title = '';
  let textPreview = '';
  if (kind === 'files') {
    const names = native.files;
    title = clampText(names.join('、'), TITLE_LIMIT) || '文件';
    textPreview = clampText(names.join('\n'), PREVIEW_LIMIT);
  } else if (kind === 'image') {
    const dimension =
      native.imageWidth > 0 && native.imageHeight > 0 ? ` ${native.imageWidth}×${native.imageHeight}` : '';
    title = clampText(`图片${dimension}`, TITLE_LIMIT);
    textPreview = clampText(text.trim() ? firstLine(text) : `图片${dimension}`, PREVIEW_LIMIT);
  } else {
    title = clampText(firstLine(text), TITLE_LIMIT);
    textPreview = clampText(collapseSpaces(text), PREVIEW_LIMIT);
  }

  let bytes = payloadBytes(snap);
  if (!bytes && text.trim()) bytes = utf8ByteLength(text);

  return { kind, title, textPreview, bytes, source: normalizeSource(snap.source) };
}

/* ---------------------------------------------------------------------------
 * 状态
 * ------------------------------------------------------------------------- */

export function createEmptyState() {
  return { schemaVersion: SCHEMA_VERSION, items: [], paused: false, ignoreNext: false };
}

function normalizeItem(raw) {
  if (!raw || typeof raw !== 'object') return null;
  const id = normalizeId(raw.id);
  if (!id) return null;

  const createdAt = clampInt(raw.createdAt, 0, Number.MAX_SAFE_INTEGER, 0);
  const pinned = raw.pinned === true;
  const pinKey = pinned && PIN_KEY.test(textOf(raw.pinKey)) ? textOf(raw.pinKey) : '';
  const item = {
    id,
    kind: CAPTURE_KINDS.includes(raw.kind) ? raw.kind : 'text',
    title: clampText(raw.title, TITLE_LIMIT),
    textPreview: clampText(raw.textPreview, PREVIEW_LIMIT),
    source: normalizeSource(raw.source),
    pinned,
    pinKey,
    createdAt,
    lastCopiedAt: clampInt(raw.lastCopiedAt, 0, Number.MAX_SAFE_INTEGER, createdAt),
    copyCount: clampInt(raw.copyCount, 1, Number.MAX_SAFE_INTEGER, 1),
    bytes: clampInt(raw.bytes, 0, Number.MAX_SAFE_INTEGER, 0),
  };
  const searchText = clampText(raw.searchText, SEARCH_TEXT_LIMIT);
  if (searchText) item.searchText = searchText;
  return item;
}

/**
 * 落盘状态 → 内存状态。只有 `null` / `undefined`（真的没有状态文件）当空历史；
 * 其余形态一律显式拒绝，不猜、不迁移、更不悄悄读成空后把用户的历史覆盖掉：
 * 非对象（含数组）、缺少或不是 1 的 `schemaVersion`、`items` 不是数组。
 */
export function normalizeState(value) {
  if (value == null) return createEmptyState();
  if (typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`剪贴板历史形态无法识别（期望对象，实际是 ${Array.isArray(value) ? 'array' : typeof value}）`);
  }
  if (value.schemaVersion !== SCHEMA_VERSION) {
    throw new Error(`不支持的剪贴板历史 schemaVersion: ${String(value.schemaVersion)}`);
  }
  if (!Array.isArray(value.items)) {
    throw new Error('剪贴板历史的 items 不是数组');
  }

  const items = [];
  const seen = new Set();
  for (const raw of value.items) {
    if (!raw) continue;
    const item = normalizeItem(raw);
    if (!item || seen.has(item.id)) continue;
    seen.add(item.id);
    items.push(item);
  }

  return {
    schemaVersion: SCHEMA_VERSION,
    items,
    paused: value.paused === true,
    ignoreNext: value.ignoreNext === true,
  };
}

function summaryToItem(summary, now) {
  if (!summary || typeof summary !== 'object') return null;
  const id = normalizeId(summary.id);
  if (!id) return null;
  const item = {
    id,
    kind: CAPTURE_KINDS.includes(summary.kind) ? summary.kind : 'text',
    title: clampText(summary.title, TITLE_LIMIT),
    textPreview: clampText(summary.textPreview, PREVIEW_LIMIT),
    source: normalizeSource(summary.source),
    pinned: false,
    pinKey: '',
    createdAt: now,
    lastCopiedAt: now,
    copyCount: 1,
    bytes: clampInt(summary.bytes, 0, Number.MAX_SAFE_INTEGER, 0),
  };
  const searchText = clampText(summary.searchText, SEARCH_TEXT_LIMIT);
  if (searchText) item.searchText = searchText;
  return item;
}

/**
 * 淘汰：保留期只清未固定的；条数上限也只数未固定的（固定条目永不因容量被挤掉）。
 * 淘汰依据是真实的 `lastCopiedAt`（最新的 N 条未固定留下），不是数组位置——老条目刚被再次复制
 * 时仍然排在数组后面，按位置淘汰会把它当成最旧的挤掉。留下的条目保持原有顺序（固定条目的相对
 * 位置不动）。
 */
export function pruneHistory(state, settings, now = Date.now()) {
  const base = normalizeState(state);
  const config = normalizeSettings(settings);
  const retentionMs = config.retentionDays > 0 ? config.retentionDays * 24 * 60 * 60 * 1000 : 0;

  const candidates = base.items.filter(
    (item) => !item.pinned && !(retentionMs > 0 && now - item.lastCopiedAt > retentionMs),
  );
  const survivors = new Set(
    candidates
      .slice()
      .sort((a, b) => b.lastCopiedAt - a.lastCopiedAt || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
      .slice(0, config.historySize)
      .map((item) => item.id),
  );
  const items = base.items.filter((item) => item.pinned || survivors.has(item.id));
  return { ...base, items };
}

/**
 * 采到一条：同一 id 只更新时间与次数（用户改过的标题、固定键都留着），新 id 插到最前，
 * 之后再按设置淘汰。`paused` 与 `ignoreNext` 在这里生效：暂停时一律不记；`ignoreNext` 表示
 * 「只跳过下一次」，这一次丢弃并把标记复位。
 */
export function recordCapture(state, summary, settings, now = Date.now()) {
  const base = normalizeState(state);
  if (base.paused) return base;
  if (base.ignoreNext) return { ...base, ignoreNext: false };

  const config = normalizeSettings(settings);
  const item = summaryToItem(summary, now);
  if (!item) return base;

  const index = base.items.findIndex((entry) => entry.id === item.id);
  let items;
  if (index >= 0) {
    const previous = base.items[index];
    const updated = {
      ...previous,
      lastCopiedAt: now,
      copyCount: Math.max(1, previous.copyCount) + 1,
    };
    if (!updated.searchText && item.searchText) updated.searchText = item.searchText;
    items = base.items.slice();
    items[index] = updated;
  } else {
    if (item.bytes > config.maxItemBytes) return base;
    items = [item, ...base.items];
  }
  return pruneHistory({ ...base, items }, config, now);
}

/**
 * 固定 / 取消固定：分配当前未被占用的最小 a-z 键。快捷键只是「顺手」的入口，按钮才是主入口，
 * 所以 26 个键用满时照样能固定，只是 `pinKey` 留空（没有快捷键）。
 */
export function togglePin(state, id) {
  const base = normalizeState(state);
  const target = normalizeId(id);
  const index = base.items.findIndex((item) => item.id === target);
  if (index < 0) return base;

  const item = base.items[index];
  const items = base.items.slice();
  if (item.pinned) {
    items[index] = { ...item, pinned: false, pinKey: '' };
    return { ...base, items };
  }
  const used = new Set(items.filter((entry) => entry.pinned && entry.pinKey).map((entry) => entry.pinKey));
  const free = PIN_KEYS.find((key) => !used.has(key)) ?? '';
  items[index] = { ...item, pinned: true, pinKey: free };
  return { ...base, items };
}

/** 改名：空白标题视为没改（不把行变成空白），其余截到 120 字。 */
export function renameItem(state, id, title) {
  const base = normalizeState(state);
  const target = normalizeId(id);
  const next = clampText(title, TITLE_LIMIT);
  const index = base.items.findIndex((item) => item.id === target);
  if (index < 0 || !next) return base;
  if (base.items[index].title === next) return base;
  const items = base.items.slice();
  items[index] = { ...base.items[index], title: next };
  return { ...base, items };
}

export function deleteItem(state, id) {
  const base = normalizeState(state);
  const target = normalizeId(id);
  if (!target) return base;
  const items = base.items.filter((item) => item.id !== target);
  if (items.length === base.items.length) return base;
  return { ...base, items };
}

export function clearHistory(state, options) {
  const base = normalizeState(state);
  if (options && options.includePinned === true) return { ...base, items: [] };
  const items = base.items.filter((item) => item.pinned);
  if (items.length === base.items.length) return base;
  return { ...base, items };
}

/* ---------------------------------------------------------------------------
 * 查询
 * ------------------------------------------------------------------------- */

function isSubsequence(needle, haystack) {
  let cursor = 0;
  for (const char of haystack) {
    if (char === needle[cursor]) cursor += 1;
    if (cursor >= needle.length) return true;
  }
  return needle.length === 0;
}

function haystackOf(item, fullText) {
  const extra =
    (fullText && typeof fullText.get === 'function' ? fullText.get(item.id) : '') ||
    (typeof item.searchText === 'string' ? item.searchText : '');
  const parts = [item.title, item.textPreview, item.source.name, item.source.bundleId];
  if (extra) parts.push(extra);
  return parts.filter(Boolean).join('\n').toLowerCase();
}

function compareItems(sortBy) {
  return (a, b) => {
    if (a.pinned !== b.pinned) return a.pinned ? -1 : 1;
    if (a.pinned && b.pinned) {
      if (a.pinKey !== b.pinKey) return a.pinKey < b.pinKey ? -1 : 1;
    }
    if (sortBy === 'copyCount') {
      if (a.copyCount !== b.copyCount) return b.copyCount - a.copyCount;
    } else if (sortBy === 'firstCopiedAt') {
      if (a.createdAt !== b.createdAt) return b.createdAt - a.createdAt;
    }
    if (a.lastCopiedAt !== b.lastCopiedAt) return b.lastCopiedAt - a.lastCopiedAt;
    return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
  };
}

/**
 * 查历史：`{ query, filter }` + 生效设置，第 4 个参数是「按需加载的全文」`Map<id, string>`。
 * 返回的 `items` 已按「固定优先（按快捷键稳定排序）→ 其余按 sortBy」排好；正则写错时回 `error`
 * 而不是抛错，界面照常能画。
 */
export function searchHistory(state, options, settings, fullText) {
  const base = normalizeState(state);
  const config = normalizeSettings(settings);
  const query = textOf(options?.query).trim();
  const filter = HISTORY_FILTERS.includes(options?.filter) ? options.filter : 'all';

  const scoped = base.items.filter((item) => {
    if (filter === 'all') return true;
    if (filter === 'pinned') return item.pinned;
    return item.kind === filter;
  });

  let matched = scoped;
  if (query) {
    if (config.searchMode === 'regexp') {
      let pattern;
      try {
        pattern = new RegExp(query, 'i');
      } catch (error) {
        return {
          items: [],
          total: 0,
          pinnedCount: 0,
          error: `正则表达式无效：${error instanceof Error ? error.message : String(error)}`,
        };
      }
      matched = scoped.filter((item) => pattern.test(haystackOf(item, fullText)));
    } else if (config.searchMode === 'simple') {
      const needle = query.toLowerCase();
      matched = scoped.filter((item) => haystackOf(item, fullText).includes(needle));
    } else {
      const needle = query.toLowerCase();
      matched = scoped.filter((item) => isSubsequence(needle, haystackOf(item, fullText)));
    }
  }

  const items = matched.slice().sort(compareItems(config.sortBy));
  return {
    items: items.map((item) => ({ ...item, source: { ...item.source } })),
    total: items.length,
    pinnedCount: items.filter((item) => item.pinned).length,
  };
}
