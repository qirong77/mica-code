/**
 * 提问策略：哪些选择与授权需要用户拍板。
 *
 * 选项结构、展示与答案处理留在 `ask_user` 的工具描述里，
 * 这里只说策略——两处都写一遍，改一处忘另一处就会自相矛盾。
 *
 * 这段话归插件：`ask_user` 停用后段落跟着消失，不会出现「提示词要求提问、工具却不在
 * 这一轮的工具表里」。
 */
export function buildAskGuidance(): string {
  return [
    '# 让用户拍板',
    '',
    '- 产品、设计或偏好有多种合理方案，或关键选择会改变目标和范围且无法从现有上下文确定时，用 `ask_user` 让用户拍板。',
    '- 操作超出现有授权，或涉及尚未获准的破坏性、不可逆变更时，先确认必要授权；已授权的可逆修改直接推进，不重复确认。',
  ].join('\n');
}

export const ASK_GUIDANCE = buildAskGuidance();
