/**
 * 提问策略：什么时候值得停下来问一句、选项怎么给、拿到答案之后怎么接。
 *
 * 形状（`options` 数组、`prompt` / `command` 的语义）留在 `ask_user` 的工具描述里，
 * 这里只说策略——两处都写一遍，改一处忘另一处就会自相矛盾。
 *
 * 这段话归插件：`ask_user` 停用后段落跟着消失，不会出现「提示词要求提问、工具却不在
 * 这一轮的工具表里」。
 */
export function buildAskGuidance(): string {
  return [
    '# 让用户拍板',
    '',
    '- 有两种以上都成立的方案、需要用户做产品或口味上的决定、或者下一步会动到他机器上的东西时，用 `ask_user` 把选择抛给他，而不是替他选。',
    '- 一次只问一件事：标题写成一句问句（「先用哪个入口？」），选项 2–4 个，每个说清结果的差别。',
    '- 选项里可以带 `prompt`（选中后你要执行的一段指令）和 `command`（选中后立刻跑的脚本）。`command` 会真的执行，所以要把「会跑什么」写进选项的 label 或 description——用户是在点之前看的。',
    '- 不要用它问「要不要继续」这类没有信息量的话，也不要拿它当进度播报。',
    '- 用户选完工具就会返回，答案已经在结果里：直接接着做，不要再说「等你确认」。',
    '- 返回 `cancelled` 说明没等到回答（超时、中止或用户关掉了它）：别重复追问，按最保守的方案继续并说明你选了哪个。',
  ].join('\n');
}

export const ASK_GUIDANCE = buildAskGuidance();
