import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';

const distDir = resolve('packages/mica-config-web/web/dist');
const outFile = resolve('packages/mica-config-web/src/server/generatedStaticAssets.ts');
const ignored = new Set(['.DS_Store']);

const files = listFiles(distDir).filter((file) => !file.endsWith('.map') && !ignored.has(file.split(sep).at(-1) ?? ''));
const assets = Object.fromEntries(
  files.map((file) => {
    const route = `/${relative(distDir, file).split(sep).join('/')}`;
    return [
      route,
      {
        contentType: getContentType(file),
        bodyBase64: readFileSync(file).toString('base64'),
      },
    ];
  }),
);

writeFileSync(
  outFile,
  `// Generated by scripts/generate-config-web-assets.mjs. Do not edit manually.\n` +
    `export type GeneratedStaticAsset = { contentType: string; bodyBase64: string };\n` +
    `export const generatedStaticAssets: Record<string, GeneratedStaticAsset> = ${JSON.stringify(assets, null, 2)};\n`,
  'utf-8',
);

console.log(`Generated ${files.length} config web assets: ${outFile}`);

function listFiles(dir) {
  const entries = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) entries.push(...listFiles(path));
    else entries.push(path);
  }
  return entries;
}

function getContentType(file) {
  if (file.endsWith('.html')) return 'text/html; charset=utf-8';
  if (file.endsWith('.js')) return 'text/javascript; charset=utf-8';
  if (file.endsWith('.css')) return 'text/css; charset=utf-8';
  if (file.endsWith('.json')) return 'application/json; charset=utf-8';
  if (file.endsWith('.svg')) return 'image/svg+xml';
  if (file.endsWith('.png')) return 'image/png';
  if (file.endsWith('.jpg') || file.endsWith('.jpeg')) return 'image/jpeg';
  if (file.endsWith('.woff2')) return 'font/woff2';
  return 'application/octet-stream';
}
