import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * 把 mobile-relay 的随包文件内嵌成 TS 常量。
 *
 * 随包插件跑在单二进制里，插件目录不是可执行目录，所以这些文件必须先落盘再用：
 *
 * - `agent/bridge.mjs` → `bridgeSource.ts`：本机这座桥，插件监管它；
 * - `setup.mjs` + relay 三件套 → `deploySource.ts`：在插件面板里点按钮就能接入中转机，
 *   不必让用户去命令行敲。
 *
 * 页面产物（`apps/desktop/out/renderer`）不在内嵌范围内：那是一份会随桌面端升级而过期的
 * 副本。首次部署需要它，面板会把这件事交给会话，由 agent 现场构建。
 *
 * 与 `packages/mica-pty` 的 `server.mjs` / computer-use 的 runtime 是同一套做法：
 * 源文件保持可读可跑，读的内容由本脚本生成，避免两份实现漂移。
 */
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const pluginDir = join(root, 'plugins', 'mobile-relay');

const banner = [
  '// AUTO-GENERATED by scripts/generate-mobile-relay-sources.mjs. Do not edit by hand;',
  '// run `bun scripts/generate-mobile-relay-sources.mjs` after editing the source.',
  '',
].join('\n');

function emit(file, constant, sourcePath, note) {
  const source = readFileSync(sourcePath, 'utf8');
  const outPath = join(pluginDir, file);
  writeFileSync(outPath, `${banner}${note ? `// ${note}\n` : ''}export const ${constant} = ${JSON.stringify(source)};\n`, 'utf8');
  console.log(`已生成 ${file}（${source.length} 字符）`);
}

emit('bridgeSource.ts', 'BRIDGE_SOURCE', join(pluginDir, 'agent', 'bridge.mjs'));

/** 部署用到的文件，键是落到 bundle 目录里的相对路径。 */
const DEPLOY_FILES = [
  ['setup.mjs', join(pluginDir, 'setup.mjs')],
  ['relay/relay.mjs', join(pluginDir, 'relay', 'relay.mjs')],
  ['relay/nginx-site.conf', join(pluginDir, 'relay', 'nginx-site.conf')],
  ['relay/mobile-relay.service', join(pluginDir, 'relay', 'mobile-relay.service')],
];

const bundle = {};
for (const [key, path] of DEPLOY_FILES) bundle[key] = readFileSync(path, 'utf8');

writeFileSync(
  join(pluginDir, 'deploySource.ts'),
  `${banner}export const DEPLOY_FILES: Record<string, string> = ${JSON.stringify(bundle, null, 2)};\n`,
  'utf8'
);
console.log(`已生成 deploySource.ts（${Object.keys(bundle).length} 个文件）`);
