import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'plugins', 'browser-cookie-sync')
const dir = join(root, 'extension')
const text = ['manifest.json', 'service-worker.js', 'options.html', 'options.js', 'popup.html', 'popup.js', 'README.md']
const binary = ['icons/icon16.png', 'icons/icon32.png', 'icons/icon48.png', 'icons/icon128.png']
const read = (name) => readFileSync(join(dir, name))
const files = Object.fromEntries(text.map((name) => [name, read(name).toString('utf8')]))
// PNG 不能塞进 JSON 字符串，按 base64 内嵌；安装时解码回字节。
const assets = Object.fromEntries(binary.map((name) => [name, read(name).toString('base64')]))
const version = JSON.parse(files['manifest.json']).version

/*
 * 内容指纹：`version.json` 之外的所有文件。扩展用它判断磁盘上的代码是否已经更新——
 * 只比 manifest 版本会因为「改了代码忘记升版本」而漏更新，指纹不会。
 */
const hash = createHash('sha256')
for (const name of [...text, ...binary].sort()) hash.update(name).update('\0').update(read(name)).update('\n')
const fingerprint = hash.digest('hex').slice(0, 16)

// 这个文件本身不参与指纹，只把版本与指纹带进扩展目录，运行时可自查。
files['version.json'] = `${JSON.stringify({ version, fingerprint }, null, 2)}\n`
writeFileSync(join(dir, 'version.json'), files['version.json'])

writeFileSync(
  join(root, 'extensionSources.ts'),
  `// Generated from extension/. Do not edit this file by hand.\nexport const extensionVersion = ${JSON.stringify(version)};\nexport const extensionFingerprint = ${JSON.stringify(fingerprint)};\nexport const extensionFiles: Record<string, string> = ${JSON.stringify(files, null, 2)};\nexport const extensionAssets: Record<string, string> = ${JSON.stringify(assets, null, 2)};\n`
)
