import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'plugins', 'browser-cookie-sync')
const names = ['manifest.json', 'service-worker.js', 'options.html', 'options.js', 'README.md']
const files = Object.fromEntries(names.map((name) => [name, readFileSync(join(root, 'extension', name), 'utf8')]))
writeFileSync(
  join(root, 'extensionSources.ts'),
  `// Generated from extension/. Do not edit this file by hand.\nexport const extensionFiles: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`
)
